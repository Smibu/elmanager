    private readonly HashSet<Key> _pressedKeys = new();

    public bool IsKeyDown(ModifierKey key) => key switch
    {
        ModifierKey.LeftCtrl => _pressedKeys.Contains(Key.LeftCtrl),
        ModifierKey.LeftShift => _pressedKeys.Contains(Key.LeftShift),
        ModifierKey.LeftAlt => _pressedKeys.Contains(Key.LeftAlt),
        _ => false
    };

    public bool IsKeyDown(EditorKey key) => _pressedKeys.Contains(ToAvaloniaKey(key));

    public void OnKeyDown(Key key) => _pressedKeys.Add(key);
    public void OnKeyUp(Key key) => _pressedKeys.Remove(key);
    public void Clear() => _pressedKeys.Clear();

